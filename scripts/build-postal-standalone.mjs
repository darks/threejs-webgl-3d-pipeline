import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

const root=fileURLToPath(new URL('../',import.meta.url));
const source=path.join(root,'examples/postal-diorama');
// Bundle from the editable project, never maintain a second copy of its scene code.
const result=await build({
  configFile:false,root:source,base:'./',logLevel:'warn',
  build:{write:false,target:'esnext',cssCodeSplit:false,assetsInlineLimit:Infinity,
    rollupOptions:{input:path.join(source,'index.html'),output:{inlineDynamicImports:true}}},
});
const output=(Array.isArray(result)?result:[result]).flatMap(r=>r.output);
const htmlAsset=output.find(x=>x.fileName==='index.html');assert.ok(htmlAsset);
let html=String(htmlAsset.source);
html=html.replace(/<script\b[^>]*\bsrc="([^"]+)"[^>]*><\/script>/g,(_,url)=>{
  const chunk=output.find(x=>x.fileName===url.replace(/^\.\//,''));
  assert.ok(chunk?.type==='chunk',`Missing script: ${url}`);
  assert.equal(chunk.imports.length,0,'Standalone chunk still imports external files');
  assert.equal(chunk.dynamicImports.length,0,'Standalone chunk still loads dynamic imports');
  return '<script type="module">'+chunk.code.replace(/<\/script/gi,'<\\/script')+'</script>';
});
html=html.replace(/<link\b[^>]*\brel="stylesheet"[^>]*>/g,tag=>{
  const url=tag.match(/href="([^"]+)"/)?.[1];
  const asset=output.find(x=>x.fileName===url?.replace(/^\.\//,''));assert.ok(asset,`Missing CSS: ${url}`);
  return '<style>'+String(asset.source).replace(/<\/style/gi,'<\\/style')+'</style>';
});
html=html.replace(/<link\b[^>]*\brel="modulepreload"[^>]*>/g,'');
const license=fs.readFileSync(path.join(root,'licenses/threejs.txt'),'utf8');
html=html.replace('<head>','<head>\n<!-- Generated by npm run build:postal; edit examples/postal-diorama instead.\nBundled Three.js license:\n'+license+'\n-->\n');
assert.ok(!/<script\b[^>]*\bsrc=/i.test(html),'External script remains');
assert.ok(!/<link\b[^>]*\brel="stylesheet"/i.test(html),'External stylesheet remains');
assert.match(html,/Permission is hereby granted/);
const target=path.join(root,'examples/postal.html');fs.writeFileSync(target,html);
console.log(`Generated examples/postal.html (${Buffer.byteLength(html)} bytes); JS, CSS and Three.js embedded.`);
